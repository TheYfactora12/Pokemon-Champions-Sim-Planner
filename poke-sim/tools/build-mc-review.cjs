// Review-only reference inventory. Never promotes competitive legality.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const upstream = path.join(root, 'artifacts/showdown-mc-reference');
const pin = 'efe4948570d5e8189751792136d26e71710c6c66';
if (execFileSync('git', ['-C', upstream, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim() !== pin) throw Error('Wrong reference pin');
if (execFileSync('git', ['-C', upstream, 'status', '--porcelain', '--untracked-files=no'], {encoding:'utf8'}).trim()) throw Error('Modified reference');
const { Dex } = require(path.join(upstream, 'dist/sim'));
const dex = Dex.mod('champions');
const id = value => String(value || '').toLowerCase().replace(/[^a-z0-9]/g, '');
const species = {};
for (const s of dex.species.all()) {
  if (!s.exists) continue;
  species[s.id] = {available: !s.isNonstandard, name:s.name,
    moves: s.isNonstandard ? [] : [...dex.species.getMovePool(s.id)].sort(),
    abilities:[...new Set(Object.values(s.abilities).concat(s.isMega ? Object.values(dex.species.get(s.baseSpecies).abilities) : []).map(id))]};
}
const data = {regulation:'champions_reg_m_c_2026', pin, competitive_use:false,
  species, items:dex.items.all().filter(i=>i.exists && !i.isNonstandard).map(i=>i.id).sort()};
fs.writeFileSync(path.join(root, 'generated/mc_review_reference.js'),
  '// Generated by tools/build-mc-review.cjs; reference review only.\nvar MC_REVIEW_REFERENCE = ' + JSON.stringify(data) + ';\n');
