// Review-only reference inventory. Never promotes competitive legality.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const upstream = path.join(root, 'artifacts/showdown-mc-reference');
const pin = 'efe4948570d5e8189751792136d26e71710c6c66';
if (execFileSync('git', ['-C', upstream, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim() !== pin) throw Error('Wrong reference pin');
if (execFileSync('git', ['-C', upstream, 'status', '--porcelain', '--untracked-files=no'], {encoding:'utf8'}).trim()) throw Error('Modified reference');
const { Dex } = require(path.join(upstream, 'dist/sim'));
const dex = Dex.mod('champions');
const {registeredForm,buildCandidates}=require('./mc-mega-candidates.cjs');
// The inventory verifier also binds compiled bytes to the captured reference.
const inventory = require('./audit-mc-release-inventory.cjs').audit(root);
const moves = {};
for (const row of inventory.categories.moves.filter(row => row.differences.length)) {
  const move = dex.moves.get(row.id);
  moves[row.id] = {type:move.type, basePower:move.basePower, accuracy:move.accuracy, pp:move.pp};
}
const id = value => String(value || '').toLowerCase().replace(/[^a-z0-9]/g, '');
const species = {};
for (const s of dex.species.all()) {
  if (!s.exists) continue;
  species[s.id] = {available: !s.isNonstandard, name:s.name,
    moves: s.isNonstandard ? [] : [...dex.species.getMovePool(s.id)].sort(),
    abilities:[...new Set(Object.values(s.abilities).concat(s.isMega && !s.isNonstandard ? Object.values(registeredForm(dex,s).abilities) : s.isMega ? Object.values(dex.species.get(s.baseSpecies).abilities) : []).map(id))]};
}
// Only individually reviewed lifecycle candidates; absent forms remain blocked.
const megas = {};
for (const name of ['Raichu-Mega-X','Raichu-Mega-Y','Salamence-Mega']) {
  const row=dex.species.get(name),base=dex.species.get(row.baseSpecies);
  megas[name]={baseSpecies:row.baseSpecies,megaName:row.name,megaStone:row.requiredItem,
    types:row.types,megaBaseStats:row.baseStats,ability:row.abilities['0'],
    baseAbility:base.abilities['0'],weightkg:row.weightkg};
}
const data = {regulation:'champions_reg_m_c_2026', pin, competitive_use:false,
  species, moves, megas, items:dex.items.all().filter(i=>i.exists && !i.isNonstandard).map(i=>i.id).sort()};
// Candidate descriptors are retained outside runtime assets and never added to
// the executable whitelist. Exact identity does not establish ability behavior.
const vm=require('node:vm'),legacy=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root,'data.js'),'utf8'),legacy);
const candidates={schema_version:'champions-mc-mega-candidates-v1',regulation:data.regulation,
  pin,compiled_fingerprint:inventory.compiled_fingerprint,competitive_use:false,execution_enabled:false,
  scope:'Pinned reference descriptor and alias preparation only; no runtime activation or current-client proof.',
  candidates:buildCandidates(dex,legacy.CHAMPIONS_MEGAS)};
fs.writeFileSync(path.join(root,'source/reg-m-c-mega-descriptor-candidates.json'),JSON.stringify(candidates,null,2)+'\n');
const output = '// Generated by tools/build-mc-review.cjs; reference review only.\nvar MC_REVIEW_REFERENCE = ' + JSON.stringify(data) + ';\n';
fs.writeFileSync(path.join(root, 'generated/mc_review_reference.js'), output);
const hash=require('node:crypto').createHash('sha256').update(output).digest('hex');
const manifestPath=path.join(root,'release_manifest.js'),manifest=fs.readFileSync(manifestPath,'utf8');
if (!/reference_artifact_sha256: '[a-f0-9]{64}'/.test(manifest)) throw Error('Reference identity field missing');
fs.writeFileSync(manifestPath,manifest.replace(/reference_artifact_sha256: '[a-f0-9]{64}'/,"reference_artifact_sha256: '"+hash+"'"));
