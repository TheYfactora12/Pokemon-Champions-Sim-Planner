// Review-only reference inventory. Never promotes competitive legality.
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const upstream = path.join(root, 'artifacts/showdown-mc-reference');
const pin = 'efe4948570d5e8189751792136d26e71710c6c66';
// Offline one-pair correction of the already captured artifact. This path never
// regenerates other inventory from an unavailable or different upstream checkout.
if (process.argv.includes('--pair-delta-only')) {
  const crypto=require('node:crypto'),vm=require('node:vm');
  const artifact=path.join(root,'generated/mc_review_reference.js');
  const manifestPath=path.join(root,'release_manifest.js');
  const before=fs.readFileSync(artifact,'utf8'),manifest=fs.readFileSync(manifestPath,'utf8');
  const expected=manifest.match(/reference_artifact_sha256: '([a-f0-9]{64})'/);
  if(!expected || crypto.createHash('sha256').update(before).digest('hex')!==expected[1]) throw Error('Reference artifact identity mismatch');
  const ctx=vm.createContext({});vm.runInContext(before,ctx);
  const data=JSON.parse(JSON.stringify(ctx.MC_REVIEW_REFERENCE));
  if(data.pin!==pin || data.competitive_use!==false) throw Error('Wrong base artifact');
  const helper=require('./mc-reference-pair-delta.cjs');
  // Rebuild the same correction idempotently; reject unknown preexisting deltas.
  if(data.source_deltas) {
    if(data.source_deltas.length!==1 || data.source_deltas[0].schema_version!=='mc-reference-pair-delta-v1') throw Error('Unreviewed existing deltas');
    data.species.sirfetchd.moves=data.species.sirfetchd.moves.filter(m=>m!=='meteorassault');
    delete data.source_deltas;
  }
  const delta=JSON.parse(fs.readFileSync(path.join(root,'source/mc-reference-pair-delta.json'),'utf8'));
  const baseline='// Generated by tools/build-mc-review.cjs; reference review only.\nvar MC_REVIEW_REFERENCE = '+JSON.stringify(data)+';\n';
  if(crypto.createHash('sha256').update(baseline).digest('hex')!==delta.base_artifact_sha256) throw Error('Base artifact differs from reviewed delta');
  data.source_deltas=[helper.applyPairDelta(root,data.species,pin)];
  const output='// Generated by tools/build-mc-review.cjs; reference review only.\nvar MC_REVIEW_REFERENCE = '+JSON.stringify(data)+';\n';
  const hash=crypto.createHash('sha256').update(output).digest('hex');
  fs.writeFileSync(artifact,output);
  fs.writeFileSync(manifestPath,manifest.replace(/reference_artifact_sha256: '[a-f0-9]{64}'/,"reference_artifact_sha256: '"+hash+"'"));
  process.exit(0);
}
if (execFileSync('git', ['-C', upstream, 'rev-parse', 'HEAD'], {encoding:'utf8'}).trim() !== pin) throw Error('Wrong reference pin');
if (execFileSync('git', ['-C', upstream, 'status', '--porcelain', '--untracked-files=no'], {encoding:'utf8'}).trim()) throw Error('Modified reference');
const { Dex } = require(path.join(upstream, 'dist/sim'));
const dex = Dex.mod('champions');
const {registeredForm,buildCandidates,CANDIDATE_NAMES}=require('./mc-mega-candidates.cjs');
// The inventory verifier also binds compiled bytes to the captured reference.
const inventory = require('./audit-mc-release-inventory.cjs').audit(root);
const moves = {};
for (const row of inventory.categories.moves.filter(row => row.differences.length)) {
  const move = dex.moves.get(row.id);
  moves[row.id] = {type:move.type, basePower:move.basePower, accuracy:move.accuracy, pp:move.pp};
}
const id = value => String(value || '').toLowerCase().replace(/[^a-z0-9]/g, '');
const species = {};
for (const s of dex.species.all()) {
  if (!s.exists) continue;
  species[s.id] = {available: !s.isNonstandard, name:s.name,
    moves: s.isNonstandard ? [] : [...dex.species.getMovePool(s.id)].sort(),
    abilities:[...new Set(Object.values(s.abilities).concat(s.isMega && !s.isNonstandard ? Object.values(registeredForm(dex,s).abilities) : s.isMega ? Object.values(dex.species.get(s.baseSpecies).abilities) : []).map(id))]};
}
// Only individually reviewed lifecycle candidates; absent forms remain blocked.
const megas = {};
for (const name of ['Raichu-Mega-X','Raichu-Mega-Y','Salamence-Mega',...CANDIDATE_NAMES]) {
  const row=dex.species.get(name),base=registeredForm(dex,row);
  megas[name]={baseSpecies:base.name,megaName:row.name,megaStone:row.requiredItem,
    types:row.types,megaBaseStats:row.baseStats,ability:row.abilities['0'],
    baseAbility:base.abilities['0'],baseAbilities:Object.values(base.abilities),weightkg:row.weightkg,
    execution_enabled:true};
}
const source_deltas = [require('./mc-reference-pair-delta.cjs').applyPairDelta(root,species,pin)];
const data = {regulation:'champions_reg_m_c_2026', pin, competitive_use:false,
  species, moves, megas, notrace:dex.abilities.all().filter(a=>a.flags.notrace).map(a=>a.name).sort(),
  items:dex.items.all().filter(i=>i.exists && !i.isNonstandard).map(i=>i.id).sort()};
data.source_deltas = source_deltas;
// Preserve the original offline preparation packet separately from executable
// reference descriptors. Exact identity does not establish ability behavior.
const vm=require('node:vm'),legacy=vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(root,'data.js'),'utf8'),legacy);
const candidates={schema_version:'champions-mc-mega-candidates-v1',regulation:data.regulation,
  pin,compiled_fingerprint:inventory.compiled_fingerprint,competitive_use:false,execution_enabled:false,
  scope:'Pinned reference descriptor and alias preparation only; no runtime activation or current-client proof.',
  candidates:buildCandidates(dex,legacy.CHAMPIONS_MEGAS)};
fs.writeFileSync(path.join(root,'source/reg-m-c-mega-descriptor-candidates.json'),JSON.stringify(candidates,null,2)+'\n');
const output = '// Generated by tools/build-mc-review.cjs; reference review only.\nvar MC_REVIEW_REFERENCE = ' + JSON.stringify(data) + ';\n';
fs.writeFileSync(path.join(root, 'generated/mc_review_reference.js'), output);
const hash=require('node:crypto').createHash('sha256').update(output).digest('hex');
const manifestPath=path.join(root,'release_manifest.js'),manifest=fs.readFileSync(manifestPath,'utf8');
if (!/reference_artifact_sha256: '[a-f0-9]{64}'/.test(manifest)) throw Error('Reference identity field missing');
fs.writeFileSync(manifestPath,manifest.replace(/reference_artifact_sha256: '[a-f0-9]{64}'/,"reference_artifact_sha256: '"+hash+"'"));
